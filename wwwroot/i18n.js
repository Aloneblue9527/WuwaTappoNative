  let locale = 'zh';
  const normalize = value => {
    const v = String(value || '').trim().toLowerCase();
    if (v.startsWith('en')) return 'en';
    if (v.startsWith('ja') || v.startsWith('jp')) return 'ja';
    return 'zh';
  };
  const t = (key, fallback, vars) => {
    let text = dict[locale]?.[key];
    if (text == null) text = fallback != null ? fallback : key;
    if (vars && typeof text === 'string') {
      for (const [name, value] of Object.entries(vars)) {
        text = text.split('{' + name + '}').join(String(value));
      }
    }
    return text;
  };
  const setLocale = value => {
    locale = normalize(value);
    document.documentElement.lang = locale === 'zh' ? 'zh-CN' : locale;
  };
  const applyStatic = root => {
    const scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach(el => {
      if (el.dataset.i18nOriginalText == null) el.dataset.i18nOriginalText = el.textContent;
      el.textContent = t(el.dataset.i18n, el.dataset.i18nOriginalText);
    });
    scope.querySelectorAll('[data-i18n-title]').forEach(el => {
      if (el.dataset.i18nOriginalTitle == null) el.dataset.i18nOriginalTitle = el.title;
      el.title = t(el.dataset.i18nTitle, el.dataset.i18nOriginalTitle);
    });
    scope.querySelectorAll('[data-i18n-aria]').forEach(el => {
      if (el.dataset.i18nOriginalAria == null) el.dataset.i18nOriginalAria = el.getAttribute('aria-label') || '';
      el.setAttribute('aria-label', t(el.dataset.i18nAria, el.dataset.i18nOriginalAria));
    });
  };
